"""Pure generated-unit format policy, not a mock of Linux permissions."""
import importlib.util
from pathlib import Path
import unittest

spec=importlib.util.spec_from_file_location('staging_install',Path(__file__).resolve().parents[1]/'webdesktop-deploy/scripts/staging_install.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
VALID='''# Automatically generated by systemd-fstab-generator
[Unit]
DefaultDependencies=no
BindsTo=%i.mount
Conflicts=shutdown.target
After=systemd-repart.service %i.mount
Before=shutdown.target local-fs.target
After=systemd-remount-fs.service
[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/lib/systemd/systemd-growfs /
TimeoutSec=0
'''


class GeneratedUnitPolicyTests(unittest.TestCase):
    def test_known_root_generator(self): self.assertTrue(m.known_root_growfs(VALID))
    def test_no_extra_root_commands(self): self.assertFalse(m.known_root_growfs(VALID+'ExecStartPre=/bin/sh -c arbitrary\n'))
    def test_no_environment_injection(self): self.assertFalse(m.known_root_growfs(VALID+'Environment=ARBITRARY=1\n'))
    def test_no_other_mount(self): self.assertFalse(m.known_root_growfs(VALID.replace('systemd-growfs /\n','systemd-growfs /home\n')))
    def test_no_unknown_generator(self): self.assertFalse(m.known_root_growfs(VALID.replace('systemd-fstab-generator','unknown-generator')))


if __name__=='__main__': unittest.main()
